"""Real STM32 build / flash / device-detection.

Shells out to PlatformIO (build + flash) and OpenOCD (ST-Link detection over SWD)
against the on-disk project workspace that GitManager already materializes at
``backend/data/workspaces/<project_id>/``. Mirrors the ``subprocess.run`` pattern
in :mod:`agent.git_manager`.

Toolchain resolution favors an app-owned PlatformIO/OpenOCD so the shipped app
needs no manual installs:
  - PlatformIO: ``$PIO_BIN`` -> app venv ``data/penv/bin/pio`` -> ``~/.platformio``.
    If none exist, :func:`ensure_platformio` auto-provisions one into ``data/penv``.
  - OpenOCD: ``$OPENOCD_BIN`` -> vendored ``vendor/openocd/<platform>/bin/openocd``
    -> ``openocd`` on PATH.

Default target is the STM32F103C8 Blue Pill flashed via ST-Link.
"""

from __future__ import annotations

import os
import subprocess
import sys
import time
from pathlib import Path

from schemas import BuildResult, DeviceStatus, FlashResult

BACKEND_DIR = Path(__file__).resolve().parent.parent
DATA_DIR = BACKEND_DIR / "data"
WORKSPACES_DIR = DATA_DIR / "workspaces"
PENV_DIR = DATA_DIR / "penv"
VENDOR_DIR = BACKEND_DIR / "vendor"

DEFAULT_BOARD = "bluepill_f103c8"
DEFAULT_BOARD_LABEL = "STM32F103 (Blue Pill)"

# Bound the time any single shelled command may run so a stuck probe/build can't
# hang a request forever.
DETECT_TIMEOUT_S = 15
BUILD_TIMEOUT_S = 600
FLASH_TIMEOUT_S = 180

_PLATFORMIO_INI = """; Auto-generated by HardcoreAI — edit to retarget.
[env:{env}]
platform = ststm32
board = {board}
framework = stm32cube
upload_protocol = stlink
debug_tool = stlink
""".format(env=DEFAULT_BOARD, board=DEFAULT_BOARD)


# ---------------------------------------------------------------------------
# Toolchain resolution
# ---------------------------------------------------------------------------


def _platform_slug() -> str:
    if sys.platform.startswith("win"):
        return "windows"
    if sys.platform == "darwin":
        return "macos"
    return "linux"


def _pio_candidates() -> list[Path]:
    exe = "pio.exe" if sys.platform.startswith("win") else "pio"
    bin_dir = "Scripts" if sys.platform.startswith("win") else "bin"
    return [
        PENV_DIR / bin_dir / exe,
        Path.home() / ".platformio" / "penv" / bin_dir / exe,
    ]


def pio_bin() -> str | None:
    """Resolve an existing PlatformIO executable, or None if not installed yet."""
    override = os.environ.get("PIO_BIN")
    if override and Path(override).exists():
        return override
    for cand in _pio_candidates():
        if cand.exists():
            return str(cand)
    return None


def openocd_bin() -> str:
    """Resolve OpenOCD: env override -> vendored -> PATH (`openocd`)."""
    override = os.environ.get("OPENOCD_BIN")
    if override:
        return override
    exe = "openocd.exe" if sys.platform.startswith("win") else "openocd"
    vendored = VENDOR_DIR / "openocd" / _platform_slug() / "bin" / exe
    if vendored.exists():
        return str(vendored)
    return "openocd"


def ensure_platformio() -> str:
    """Return a usable `pio` path, provisioning an app-owned core if needed.

    Creates ``data/penv`` and ``pip install platformio`` into it on first use so
    the end user never installs anything manually. Raises RuntimeError on failure.
    """
    found = pio_bin()
    if found:
        return found

    bin_dir = "Scripts" if sys.platform.startswith("win") else "bin"
    exe = "pio.exe" if sys.platform.startswith("win") else "pio"
    PENV_DIR.parent.mkdir(parents=True, exist_ok=True)

    # Build an isolated venv and install PlatformIO into it.
    venv = subprocess.run(
        [sys.executable, "-m", "venv", str(PENV_DIR)],
        capture_output=True, text=True,
    )
    if venv.returncode != 0:
        raise RuntimeError(f"Could not create PlatformIO venv:\n{venv.stderr}")

    py = PENV_DIR / bin_dir / ("python.exe" if sys.platform.startswith("win") else "python")
    install = subprocess.run(
        [str(py), "-m", "pip", "install", "-U", "platformio"],
        capture_output=True, text=True,
    )
    if install.returncode != 0:
        raise RuntimeError(f"Could not install PlatformIO:\n{install.stdout}\n{install.stderr}")

    pio = PENV_DIR / bin_dir / exe
    if not pio.exists():
        raise RuntimeError("PlatformIO installed but `pio` executable not found.")
    return str(pio)


# ---------------------------------------------------------------------------
# Workspace helpers
# ---------------------------------------------------------------------------


def workspace_dir(project_id: str) -> Path:
    """Directory to build/flash in — the same one GitManager syncs DB files into.

    Resolves to the project's real on-disk folder (``project.path``) when one is
    set, so build artifacts (platformio.ini, .pio/) land next to the user's code
    where they expect them. Falls back to the internal ``data/workspaces/<id>``
    only for projects with no real path (mirrors GitManager's resolution).
    """
    if str(project_id).isdigit():
        try:
            from db.session import engine
            from sqlmodel import Session, select
            from db.models import ProjectRow
            with Session(engine) as session:
                project = session.exec(
                    select(ProjectRow).where(ProjectRow.id == int(project_id))
                ).first()
                # Match GitManager's resolution exactly: use the real folder only
                # when it is an initialized repo, otherwise the internal workspace.
                # This guarantees the build dir is the same one sync writes into.
                if project and project.path and (Path(project.path) / ".git").exists():
                    return Path(project.path)
        except Exception:
            # Never let DB lookup failure break a build — fall back to internal ws.
            pass
    return WORKSPACES_DIR / str(project_id)


def ensure_platformio_ini(workspace: Path, board: str = DEFAULT_BOARD) -> None:
    """Write a platformio.ini if the project doesn't already ship one."""
    ini = workspace / "platformio.ini"
    if not ini.exists():
        workspace.mkdir(parents=True, exist_ok=True)
        ini.write_text(_PLATFORMIO_INI, encoding="utf-8")


def _find_firmware(workspace: Path) -> str | None:
    build_dir = workspace / ".pio" / "build"
    if not build_dir.exists():
        return None
    for ext in ("*.elf", "*.bin", "*.hex"):
        for fw in build_dir.rglob(ext):
            return str(fw)
    return None


# ---------------------------------------------------------------------------
# Detection
# ---------------------------------------------------------------------------


def detect_device() -> DeviceStatus:
    """Probe for an ST-Link over SWD using OpenOCD.

    Runs a minimal ``init; exit`` against the ST-Link interface + stm32f1x target.
    A clean init means the adapter saw a debuggable target. Never raises — returns
    a DeviceStatus describing the outcome (including missing-toolchain).
    """
    cmd = [
        openocd_bin(),
        "-f", "interface/stlink.cfg",
        "-f", "target/stm32f1x.cfg",
        "-c", "init; exit",
    ]
    try:
        res = subprocess.run(cmd, capture_output=True, text=True, timeout=DETECT_TIMEOUT_S)
    except FileNotFoundError:
        return DeviceStatus(connected=False, detail="OpenOCD not found (flash tooling unavailable).")
    except subprocess.TimeoutExpired:
        return DeviceStatus(connected=False, detail="Device probe timed out.")

    # OpenOCD prints diagnostics on stderr. Heuristics: success markers vs the
    # well-known "no device" / "unable to open" failures.
    blob = f"{res.stdout}\n{res.stderr}".lower()
    if res.returncode == 0 and ("stlink" in blob or "target voltage" in blob) and "error" not in blob:
        return DeviceStatus(
            connected=True,
            probe="ST-Link V2",
            target=DEFAULT_BOARD_LABEL,
            detail="ST-Link detected over SWD.",
        )
    if "no device found" in blob or "unable to open" in blob or "libusb_open" in blob:
        return DeviceStatus(connected=False, probe="ST-Link V2", detail="No ST-Link/board connected.")
    # Adapter present but target not reachable (e.g. board unpowered).
    if "stlink" in blob and "init mode failed" in blob:
        return DeviceStatus(
            connected=False, probe="ST-Link V2",
            detail="ST-Link present but no target detected (check wiring/power).",
        )
    return DeviceStatus(connected=False, detail=(res.stderr or res.stdout or "No device detected.").strip()[:500])


# ---------------------------------------------------------------------------
# Build / flash
# ---------------------------------------------------------------------------


def build_project(project_id: str, board: str = DEFAULT_BOARD) -> BuildResult:
    """Run a real PlatformIO build in the project workspace. Always returns output."""
    workspace = workspace_dir(project_id)
    if not workspace.exists():
        return BuildResult(success=False, returncode=1,
                            output="Workspace not found — sync project files first.")

    try:
        pio = ensure_platformio()
    except RuntimeError as exc:
        return BuildResult(success=False, returncode=127,
                           output=f"Toolchain unavailable: {exc}")

    ensure_platformio_ini(workspace, board)

    started = time.monotonic()
    try:
        res = subprocess.run(
            [pio, "run", "-d", str(workspace)],
            capture_output=True, text=True, timeout=BUILD_TIMEOUT_S,
        )
    except subprocess.TimeoutExpired:
        return BuildResult(success=False, returncode=124,
                           output="Build timed out.", duration_s=time.monotonic() - started)

    output = (res.stdout or "") + (res.stderr or "")
    return BuildResult(
        success=res.returncode == 0,
        returncode=res.returncode,
        output=output,
        firmware_path=_find_firmware(workspace) if res.returncode == 0 else None,
        duration_s=round(time.monotonic() - started, 2),
    )


def build_project_stream(project_id: str, board: str = DEFAULT_BOARD):
    """Run a real PlatformIO build, yielding output line-by-line as it runs.

    Yields dicts:
      {"type": "line", "text": str}                      one stdout/stderr line
      {"type": "status", "text": str}                    lifecycle notes (e.g. provisioning)
      {"type": "done", "success": bool, "returncode": int,
       "firmware_path": str|None, "duration_s": float,
       "output": str}                                    terminal event w/ full log

    Generator (blocking I/O); a caller should iterate it on a worker thread and
    forward events to the client. Never raises — failures surface as a done event.
    """
    workspace = workspace_dir(project_id)
    if not workspace.exists():
        yield {"type": "done", "success": False, "returncode": 1,
               "firmware_path": None, "duration_s": 0.0,
               "output": "Workspace not found — sync project files first."}
        return

    try:
        yield {"type": "status", "text": "Resolving build toolchain (PlatformIO)…"}
        pio = ensure_platformio()
    except RuntimeError as exc:
        yield {"type": "done", "success": False, "returncode": 127,
               "firmware_path": None, "duration_s": 0.0,
               "output": f"Toolchain unavailable: {exc}"}
        return

    ensure_platformio_ini(workspace, board)
    yield {"type": "status", "text": "Compiling firmware…"}

    started = time.monotonic()
    lines: list[str] = []
    try:
        proc = subprocess.Popen(
            [pio, "run", "-d", str(workspace)],
            stdout=subprocess.PIPE,
            stderr=subprocess.STDOUT,  # merge so the log reads in real order
            text=True,
            bufsize=1,  # line-buffered
        )
    except FileNotFoundError as exc:
        yield {"type": "done", "success": False, "returncode": 127,
               "firmware_path": None, "duration_s": 0.0,
               "output": f"Could not start PlatformIO: {exc}"}
        return

    try:
        assert proc.stdout is not None
        for raw in proc.stdout:
            line = raw.rstrip("\n")
            lines.append(line)
            yield {"type": "line", "text": line}
            if time.monotonic() - started > BUILD_TIMEOUT_S:
                proc.kill()
                lines.append("Build timed out.")
                yield {"type": "line", "text": "Build timed out."}
                break
        returncode = proc.wait(timeout=10)
    except Exception as exc:  # noqa: BLE001 — surface, don't crash the stream
        proc.kill()
        returncode = proc.returncode if proc.returncode is not None else 1
        lines.append(f"Build error: {exc}")
        yield {"type": "line", "text": f"Build error: {exc}"}

    success = returncode == 0
    yield {
        "type": "done",
        "success": success,
        "returncode": returncode,
        "firmware_path": _find_firmware(workspace) if success else None,
        "duration_s": round(time.monotonic() - started, 2),
        "output": "\n".join(lines),
    }


def flash_project(project_id: str, board: str = DEFAULT_BOARD) -> FlashResult:
    """Build (if needed) then flash via `pio run -t upload`, gated on detection."""
    device = detect_device()
    if not device.connected:
        return FlashResult(flashed=False, reason="no_device",
                           output=device.detail, device=device)

    workspace = workspace_dir(project_id)
    try:
        pio = ensure_platformio()
    except RuntimeError as exc:
        return FlashResult(flashed=False, reason="flash_failed",
                           returncode=127, output=f"Toolchain unavailable: {exc}", device=device)

    ensure_platformio_ini(workspace, board)
    try:
        res = subprocess.run(
            [pio, "run", "-d", str(workspace), "-t", "upload"],
            capture_output=True, text=True, timeout=FLASH_TIMEOUT_S,
        )
    except subprocess.TimeoutExpired:
        return FlashResult(flashed=False, reason="flash_failed",
                           returncode=124, output="Flash timed out.", device=device)

    output = (res.stdout or "") + (res.stderr or "")
    ok = res.returncode == 0
    return FlashResult(
        flashed=ok,
        reason="" if ok else "flash_failed",
        returncode=res.returncode,
        output=output,
        device=device,
    )
