# Families with a real, hand-verified peripheral template set below.
# Anything else raises rather than silently emitting F1 code under a
# different MCU's name — see hardcoreai-multiboard-architecture.md §11.
SUPPORTED_FAMILIES = {"STM32F1", "STM32F4", "STM32F7", "STM32L4", "STM32G4", "STM32G0",
                       "STM32H7", "STM32L0", "STM32L1", "STM32L5", "STM32WB", "STM32U5",
                       "STM32WL", "STM32F0", "STM32F3", "STM32F2", "STM32H5", "STM32C0",
                       "STM32U0", "STM32C5", "STM32WB0", "STM32WBA", "STM32U3", "STM32N6",
                       "STM32V8"}

def is_supported_family(family: str) -> bool:
    return family in SUPPORTED_FAMILIES


class UnsupportedFamilyError(Exception):
    """Raised when generate_hal_files() is asked for a board whose family
    has no real peripheral templates yet. Metadata (registry) support and
    codegen support are tracked separately — this is that boundary."""


def _resolve_meta(board: str) -> dict:
    device = registry.get(board)
    if device is None:
        # Unknown board id entirely — fall back to Blue Pill, same as
        # every other module's default, rather than crashing.
        device = registry.default()

    family = device.family
    if family not in SUPPORTED_FAMILIES:
        if family.startswith("STM32") or device.mcu.startswith("STM32"):
            family = "STM32_GENERIC"
        else:
            raise UnsupportedFamilyError(
                f"HAL code generation is not yet implemented for {device.family} "
                f"({device.label}). Currently supported: {', '.join(sorted(SUPPORTED_FAMILIES))}."
            )

    return {
        "mcu": device.mcu,
        "hal_header": device.hal_header,
        "core_clock": f"{device.f_cpu_hz}UL",
        "family": family,
    }
