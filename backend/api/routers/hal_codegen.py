def generate_hal_files(board: str, peripherals: list[dict[str, Any]]) -> dict[str, str]:
    """
    Returns a dict of { "src/hal/filename.c": "file content string" }
    for every enabled peripheral + a main_init.c orchestrator.
    """
    meta = {**_DEFAULT_META, **BOARD_META.get(board, {})}
    files: dict[str, str] = {}

    # DMA first if present (must init before other peripherals use it)
    ordered = sorted(peripherals, key=lambda p: 0 if p["id"] == "dma" else 1)

    init_calls: list[str] = []
    includes: list[str] = []

    for p in ordered:
        pid = p["id"]
        if pid not in TEMPLATES:
            continue  # unknown peripheral — silently skip

        fmt = {**meta, "mode": p.get("mode", "")}
        for rel_path, template in TEMPLATES[pid].items():
            files[rel_path] = template.format_map(fmt)

        if pid in INIT_CALLS:
            init_calls.append(INIT_CALLS[pid])
            includes.append(INCLUDES[pid])

    # Generate the top-level orchestrator that calls everything
    peripheral_names = ", ".join(p["id"].upper() for p in peripherals)
    files["src/hal/main_init.c"] = (
        f"/* main_init.c — generated by HardcoreAI for {meta['mcu']} */\n"
        f"/* Board: {board}  |  Peripherals: {peripheral_names} */\n"
        f'#include "{meta["hal_header"]}"\n'
        + "\n".join(includes) + "\n\n"
        "void HAL_Init_All(void) {\n"
        "    HAL_Init();\n"
        + "\n".join(init_calls) + "\n"
        "}\n"
    )
    files["src/hal/main_init.h"] = (
        f"/* main_init.h — generated by HardcoreAI for {meta['mcu']} */\n"
        "#pragma once\n"
        "void HAL_Init_All(void);\n"
    )

    return files