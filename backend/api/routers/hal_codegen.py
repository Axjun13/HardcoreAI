def generate_hal_files(
    board: str,
    peripherals: list[dict[str, Any]],
    pin_assignments: list[dict[str, Any]] | None = None,
) -> dict[str, str]:
    """
    Returns a dict of { "src/hal/filename.c": "file content string" }
    for every enabled peripheral + a main_init.c orchestrator.

    Raises UnsupportedFamilyError for any board whose family has no real
    template set yet (see SUPPORTED_FAMILIES) — this is intentional: it's
    safer to fail loudly than to generate code that references the right
    MCU name but has the wrong clock tree / register layout underneath.
    """
    meta = _resolve_meta(board)
    device = registry.get(board)
    family = meta["family"]
    family_templates = FAMILY_TEMPLATES.get(family)
    if family_templates is None and family.startswith("STM32"):
        family_templates = FAMILY_TEMPLATES.get("STM32_GENERIC")
    if family_templates is None:
        raise UnsupportedFamilyError(f"No template set available for family {family}")
    templates = {**COMMON_TEMPLATES, **family_templates}
    files: dict[str, str] = {}

    # DMA first if present (must init before other peripherals use it)
    ordered = sorted(peripherals, key=lambda p: 0 if p["id"] == "dma" else 1)

    init_calls: list[str] = []
    includes: list[str] = []
    pin_assignments = pin_assignments or []

    if pin_assignments:
        files.update(_generate_pinmux_files(meta, pin_assignments))
        init_calls.append("    MX_PinMux_Init();")
        includes.append('#include "hal/pinmux_init.h"')

    for p in ordered:
        pid = p["id"]
        if pid not in templates:
            continue  # unknown peripheral — silently skip

        fmt = {**meta, "mode": p.get("mode", "")}
        for rel_path, template in templates[pid].items():
            files[rel_path] = template.format_map(fmt)

        if pid in INIT_CALLS:
            init_calls.append(INIT_CALLS[pid])
            includes.append(INCLUDES[pid])

    # Generate the top-level orchestrator that calls everything
    peripheral_names = ", ".join(p["id"].upper() for p in peripherals)
    files["src/hal/main_init.c"] = (
        f"/* main_init.c — generated by HardcoreAI for {meta['mcu']} */\n"
        f"/* Board: {board}  |  Peripherals: {peripheral_names} */\n"
        f'#include "{meta["hal_header"]}"\n'
        + "\n".join(includes) + "\n\n"
        "void HAL_Init_All(void) {\n"
        "    HAL_Init();\n"
        + "\n".join(init_calls) + "\n"
        "}\n"
    )
    files["src/hal/main_init.h"] = (
        f"/* main_init.h — generated by HardcoreAI for {meta['mcu']} */\n"
        "#pragma once\n"
        "void HAL_Init_All(void);\n"
    )

    return files